# Active stop words set used by other modules to filter words
STOP_WORDS: set[str] = set(_DEFAULT_STOP_WORDS)


def reset_stop_words(custom_words: list[str] | None = None) -> None:
    """Reset the active stop words set to the default list, optionally adding custom words.

    Args:
        custom_words: List of custom stop words to add to the active set.
    """
    STOP_WORDS.clear()
    STOP_WORDS.update(_DEFAULT_STOP_WORDS)
    for word in custom_words or []:
        if cleaned := word.strip().lower():
            STOP_WORDS.add(cleaned)
